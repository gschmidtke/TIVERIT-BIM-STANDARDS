from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STANDARDS_ROOT = ROOT / "standards"
OUTPUT_ROOT = ROOT / "dist" / "human" / "standards"


def load_json(path: Path):
    with path.open("r", encoding="utf-8") as fh:
        return json.load(fh)


def format_value(value):
    if value is None:
        return "—"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (str, int, float)):
        return str(value)
    return json.dumps(value, ensure_ascii=False, sort_keys=True)


def render_requirement(requirement: dict) -> str:
    rid = requirement.get("id", "UNIDENTIFIED")
    authority = requirement.get("authority", "")
    verification = requirement.get("verification_class", "")
    statement = requirement.get("statement", "")
    lines = [f"### {rid}", ""]
    if authority:
        lines.append(f"- **Authority:** `{authority}`")
    if verification:
        lines.append(f"- **Verification:** `{verification}`")
    lines.extend(["", statement.strip(), ""])
    return "\n".join(lines)


def render_relationships(relationships: dict) -> str:
    if not relationships:
        return ""
    lines = ["## Relationships", ""]
    for key in sorted(relationships):
        value = relationships[key]
        if isinstance(value, list):
            lines.append(f"- **{key}:**")
            for item in value:
                lines.append(f"  - `{format_value(item)}`")
        else:
            lines.append(f"- **{key}:** `{format_value(value)}`")
    lines.append("")
    return "\n".join(lines)


def render_standard(obj: dict) -> str:
    lines = [
        f"# {obj.get('title', obj.get('id', 'Untitled Standard'))}",
        "",
        "> Generated from canonical repository JSON. Do not edit this file as a parallel standard.",
        "",
        "## Identity",
        "",
        f"- **ID:** `{obj.get('id', '')}`",
        f"- **Status:** `{obj.get('status', '')}`",
        f"- **Authority:** `{obj.get('authority', '')}`",
        f"- **Layer:** `{obj.get('layer', '')}`",
        f"- **Modules:** {', '.join(f'`{m}`' for m in obj.get('modules', [])) or '—'}",
    ]

    if obj.get("version"):
        lines.append(f"- **Version:** `{obj['version']}`")
    if obj.get("effective_date"):
        lines.append(f"- **Effective date:** `{obj['effective_date']}`")

    scope = obj.get("scope")
    if isinstance(scope, dict) and scope:
        lines.extend(["", "## Scope", ""])
        purpose = scope.get("purpose")
        if isinstance(purpose, str) and purpose.strip():
            lines.extend([purpose.strip(), ""])
        for key in sorted(k for k in scope if k != "purpose"):
            lines.append(f"- **{key}:** {format_value(scope[key])}")
        lines.append("")

    requirements = obj.get("requirements", [])
    if isinstance(requirements, list) and requirements:
        lines.extend(["## Requirements", ""])
        for requirement in requirements:
            if isinstance(requirement, dict):
                lines.append(render_requirement(requirement).rstrip())
                lines.append("")

    relationships = obj.get("relationships")
    if isinstance(relationships, dict):
        rendered_relationships = render_relationships(relationships)
        if rendered_relationships:
            lines.append(rendered_relationships.rstrip())
            lines.append("")

    provenance = obj.get("provenance")
    if isinstance(provenance, dict) and provenance:
        lines.extend(["## Provenance", ""])
        for key in sorted(provenance):
            lines.append(f"- **{key}:** {format_value(provenance[key])}")
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    OUTPUT_ROOT.mkdir(parents=True, exist_ok=True)
    rendered = 0

    for path in sorted(STANDARDS_ROOT.rglob("*.json")):
        obj = load_json(path)
        if not isinstance(obj, dict) or obj.get("type") != "standard":
            continue
        object_id = obj.get("id")
        if not isinstance(object_id, str) or not object_id:
            raise ValueError(f"{path.relative_to(ROOT)} has no stable standard id")
        output_path = OUTPUT_ROOT / f"{object_id}.md"
        output_path.write_text(render_standard(obj), encoding="utf-8")
        print(f"RENDERED {path.relative_to(ROOT)} -> {output_path.relative_to(ROOT)}")
        rendered += 1

    if rendered == 0:
        raise RuntimeError("No canonical standard objects were rendered")

    print(f"\nRendered standards: {rendered}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
